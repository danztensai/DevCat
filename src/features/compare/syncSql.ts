// Generate a DDL script that makes the TARGET schema match the SOURCE for the
// selected diff items, written in the target dialect.
import type { ColumnDef, ForeignKeyDef, IndexDef, TableStructure } from "../../lib/types";
import type { SchemaDiff, TableDiff, ViewDiff } from "./diff";
import { mapDefault, mapType, parseType, qualify, quoteIdent, terminator, type SqlDialect } from "./sqlDialect";

export interface SyncOptions {
  sourceDialect: SqlDialect;
  targetDialect: SqlDialect;
  sourceSchema?: string | null;
  targetSchema?: string | null;
  /** Ids (TableDiff.id / ViewDiff.id) to include. */
  selected: Set<string>;
  /** Emit DROP for objects only in target. */
  dropExtra: boolean;
  /** Emit DROP COLUMN for columns only in target. */
  dropColumns: boolean;
  /** Include a header comment block. */
  header?: string;
}

const INT_FAMILY = /^(tinyint|smallint|int|integer|bigint|int2|int4|int8|mediumint|serial|bigserial|smallserial)$/;

class Script {
  parts: string[] = [];
  private d: SqlDialect;
  constructor(d: SqlDialect) { this.d = d; }
  stmt(sql: string) { this.parts.push(sql + terminator(this.d)); }
  comment(text: string) { this.parts.push(text.split("\n").map((l) => `-- ${l}`).join("\n")); }
  blank() { if (this.parts.length && this.parts[this.parts.length - 1] !== "") this.parts.push(""); }
  section(title: string) { this.blank(); this.comment(`---- ${title} ----`); }
  toString() { return this.parts.join("\n").trim() + "\n"; }
}

export function generateSyncSql(diff: SchemaDiff, o: SyncOptions): string {
  const d = o.targetDialect;
  const q = (s: string) => quoteIdent(d, s);
  const tbl = (name: string) => qualify(d, name, o.targetSchema);
  const s = new Script(d);
  if (o.header) s.comment(o.header);
  if (o.sourceDialect !== d) s.comment(`Types mapped from ${o.sourceDialect} to ${d}. Review before executing.`);

  const tables = diff.tables.filter((t) => o.selected.has(t.id));
  const views = diff.views.filter((v) => o.selected.has(v.id));
  const creates = tables.filter((t) => t.status === "onlySource");
  const drops = o.dropExtra ? tables.filter((t) => t.status === "onlyTarget") : [];
  const alters = tables.filter((t) => t.status === "different");

  const refTable = (fk: ForeignKeyDef) => {
    const schema = !fk.refSchema || fk.refSchema === o.sourceSchema ? o.targetSchema : fk.refSchema;
    return qualify(d, fk.refTable, schema);
  };
  const fkClause = (fk: ForeignKeyDef) => {
    let sql = `FOREIGN KEY (${fk.columns.map(q).join(", ")}) REFERENCES ${refTable(fk)} (${fk.refColumns.map(q).join(", ")})`;
    const act = (a?: string | null) => a && a.toUpperCase() !== "NO ACTION" && !(d === "mssql" && a.toUpperCase() === "RESTRICT") ? a.toUpperCase() : null;
    if (act(fk.onDelete)) sql += ` ON DELETE ${act(fk.onDelete)}`;
    if (act(fk.onUpdate)) sql += ` ON UPDATE ${act(fk.onUpdate)}`;
    return sql;
  };

  const colType = (c: ColumnDef) => mapType(c.dataType, o.sourceDialect, d);

  /** Column definition without the name. `inlinePk` = sqlite single-column autoincrement PK. */
  const colDef = (c: ColumnDef, inlinePk = false) => {
    let type = colType(c);
    const isInt = INT_FAMILY.test(parseType(type).base);
    let ai = "";
    if (c.autoIncrement && !/serial/i.test(type)) {
      if (d === "postgres" && isInt) ai = " GENERATED BY DEFAULT AS IDENTITY";
      else if (d === "mysql") ai = " AUTO_INCREMENT";
      else if (d === "mssql") ai = " IDENTITY(1,1)";
    }
    if (d === "sqlite" && inlinePk) {
      return `INTEGER PRIMARY KEY${c.autoIncrement ? " AUTOINCREMENT" : ""}`;
    }
    if (d === "sqlite" && c.autoIncrement) type = "INTEGER";
    const def = c.autoIncrement ? null : mapDefault(c.default, o.sourceDialect, d);
    return `${type}${ai}${c.nullable ? (d === "mssql" ? " NULL" : "") : " NOT NULL"}${def !== null ? ` DEFAULT ${def}` : ""}`;
  };

  const indexSql = (table: string, i: IndexDef) =>
    `CREATE ${i.unique ? "UNIQUE " : ""}INDEX ${q(i.name)} ON ${tbl(table)} (${i.columns.map(q).join(", ")})`;
  const dropIndexSql = (table: string, i: IndexDef) => {
    switch (d) {
      case "postgres": return `DROP INDEX ${qualify(d, i.name, o.targetSchema)}`;
      case "sqlite": return `DROP INDEX ${q(i.name)}`;
      default: return `DROP INDEX ${q(i.name)} ON ${tbl(table)}`;
    }
  };
  const dropFkSql = (table: string, fk: ForeignKeyDef) =>
    d === "mysql" ? `ALTER TABLE ${tbl(table)} DROP FOREIGN KEY ${q(fk.name)}` : `ALTER TABLE ${tbl(table)} DROP CONSTRAINT ${q(fk.name)}`;
  const addFkSql = (table: string, fk: ForeignKeyDef) =>
    `ALTER TABLE ${tbl(table)} ADD ${fk.name ? `CONSTRAINT ${q(fk.name)} ` : ""}${fkClause(fk)}`;

  const createTableSql = (t: TableStructure, name: string, inlineFks: boolean) => {
    const cols = [...t.columns].sort((a, b) => a.ordinal - b.ordinal);
    const pk = cols.filter((c) => c.isPrimaryKey);
    const sqliteInline = d === "sqlite" && pk.length === 1 && pk[0].autoIncrement;
    const lines = cols.map((c) => `  ${q(c.name)} ${colDef(c, sqliteInline && c === pk[0])}`);
    if (pk.length && !sqliteInline) lines.push(`  PRIMARY KEY (${pk.map((c) => q(c.name)).join(", ")})`);
    if (inlineFks) for (const fk of t.foreignKeys) lines.push(`  ${fk.name ? `CONSTRAINT ${q(fk.name)} ` : ""}${fkClause(fk)}`);
    return `CREATE TABLE ${name} (\n${lines.join(",\n")}\n)`;
  };

  // 1. Drop foreign keys that go away / change (before touching columns & tables).
  if (d !== "sqlite") {
    const fkDrops = alters.flatMap((t) => t.foreignKeys
      .filter((f) => f.status === "changed" || (f.status === "onlyTarget" && o.dropExtra))
      .map((f) => dropFkSql(t.name, f.target!)));
    if (fkDrops.length) { s.section("Drop foreign keys"); fkDrops.forEach((x) => s.stmt(x)); }
  }

  // 2. Drop views only in target, and views that will be recreated if dialect needs it.
  const viewDrops = o.dropExtra ? views.filter((v) => v.status === "onlyTarget") : [];
  if (viewDrops.length) {
    s.section("Drop views");
    for (const v of viewDrops) s.stmt(`DROP VIEW ${qualify(d, v.name, o.targetSchema)}`);
  }

  // 3. Drop tables only in target.
  if (drops.length) {
    s.section("Drop tables");
    for (const t of drops) s.stmt(`DROP TABLE ${tbl(t.name)}`);
  }

  // 4. Create tables only in source.
  if (creates.length) {
    s.section("Create tables");
    for (const t of creates) {
      s.stmt(createTableSql(t.source!, tbl(t.name), d === "sqlite"));
      for (const i of t.source!.indexes.filter((x) => !x.primary)) s.stmt(indexSql(t.name, i));
      s.blank();
    }
  }

  // 5. Alter tables that differ.
  if (alters.length) s.section("Alter tables");
  for (const t of alters) alterTable(t);

  // 6. Foreign keys (new tables + added/changed) — SQLite FKs are inline only.
  if (d !== "sqlite") {
    const fkAdds: string[] = [];
    for (const t of creates) for (const fk of t.source!.foreignKeys) fkAdds.push(addFkSql(t.name, fk));
    for (const t of alters) for (const f of t.foreignKeys) if (f.status === "onlySource" || f.status === "changed") fkAdds.push(addFkSql(t.name, f.source!));
    if (fkAdds.length) { s.section("Add foreign keys"); fkAdds.forEach((x) => s.stmt(x)); }
  }

  // 7. Views.
  const viewCreates = views.filter((v) => v.status === "onlySource" || v.status === "different");
  if (viewCreates.length) {
    s.section("Views");
    for (const v of viewCreates) viewSql(v);
  }

  if (s.parts.filter((p) => !p.startsWith("--") && p !== "").length === 0) {
    s.blank();
    s.comment("Nothing to synchronize for the current selection.");
  }
  return s.toString();

  // ---------------------------------------------------------------------------

  function alterTable(t: TableDiff) {
    const name = tbl(t.name);
    s.comment(`Table ${t.name}`);
    const added = t.columns.filter((c) => c.status === "onlySource");
    const removed = o.dropColumns ? t.columns.filter((c) => c.status === "onlyTarget") : [];
    const changed = t.columns.filter((c) => c.status === "changed");

    // Index drops first (they may reference dropped/changed columns)
    for (const i of t.indexes) {
      if (i.status === "changed" || (i.status === "onlyTarget" && o.dropExtra)) s.stmt(dropIndexSql(t.name, i.target!));
    }

    if (d === "sqlite") {
      for (const c of added) {
        if (!c.source!.nullable && !c.source!.default) s.comment(`NOTE: SQLite requires a DEFAULT for NOT NULL columns added via ALTER TABLE (${c.name}).`);
        s.stmt(`ALTER TABLE ${name} ADD COLUMN ${q(c.name)} ${colDef(c.source!)}`);
      }
      for (const c of removed) s.stmt(`ALTER TABLE ${name} DROP COLUMN ${q(c.name)}`);
      const fkChanged = t.foreignKeys.some((f) => f.status !== "same");
      if (changed.length || t.pkChanged || fkChanged) sqliteRebuild(t);
    } else {
      for (const c of added) {
        s.stmt(d === "mssql"
          ? `ALTER TABLE ${name} ADD ${q(c.name)} ${colDef(c.source!)}`
          : `ALTER TABLE ${name} ADD COLUMN ${q(c.name)} ${colDef(c.source!)}`);
      }
      for (const c of changed) alterColumn(t, c.source!, c.target!, c.changes);
      if (t.pkChanged) {
        const pkCols = t.source!.columns.filter((c) => c.isPrimaryKey).map((c) => q(c.name)).join(", ");
        const hasOldPk = t.target!.columns.some((c) => c.isPrimaryKey);
        const oldPkName = t.target!.indexes.find((i) => i.primary)?.name;
        if (d === "mysql") {
          s.stmt(`ALTER TABLE ${name}${hasOldPk ? " DROP PRIMARY KEY" : ""}${hasOldPk && pkCols ? "," : ""}${pkCols ? ` ADD PRIMARY KEY (${pkCols})` : ""}`);
        } else {
          if (hasOldPk) {
            const pkName = oldPkName ?? (d === "postgres" ? `${t.name}_pkey` : `PK_${t.name}`);
            if (!oldPkName) s.comment(`Primary key constraint name assumed: ${pkName}`);
            s.stmt(`ALTER TABLE ${name} DROP CONSTRAINT ${q(pkName)}`);
          }
          if (pkCols) s.stmt(`ALTER TABLE ${name} ADD PRIMARY KEY (${pkCols})`);
        }
      }
      for (const c of removed) s.stmt(`ALTER TABLE ${name} DROP COLUMN ${q(c.name)}`);
    }

    for (const i of t.indexes) {
      if (i.status === "changed" || i.status === "onlySource") s.stmt(indexSql(t.name, i.source!));
    }
    s.blank();
  }

  function alterColumn(t: TableDiff, src: ColumnDef, tgt: ColumnDef, changes: string[]) {
    const name = tbl(t.name);
    const col = q(src.name);
    const type = colType(src);
    switch (d) {
      case "postgres": {
        if (changes.includes("type")) s.stmt(`ALTER TABLE ${name} ALTER COLUMN ${col} TYPE ${type} USING ${col}::${type}`);
        if (changes.includes("nullable")) s.stmt(`ALTER TABLE ${name} ALTER COLUMN ${col} ${src.nullable ? "DROP NOT NULL" : "SET NOT NULL"}`);
        if (changes.includes("default")) {
          const def = mapDefault(src.default, o.sourceDialect, d);
          s.stmt(`ALTER TABLE ${name} ALTER COLUMN ${col} ${def !== null ? `SET DEFAULT ${def}` : "DROP DEFAULT"}`);
        }
        if (changes.includes("autoIncrement")) {
          s.stmt(src.autoIncrement
            ? `ALTER TABLE ${name} ALTER COLUMN ${col} ADD GENERATED BY DEFAULT AS IDENTITY`
            : `ALTER TABLE ${name} ALTER COLUMN ${col} DROP IDENTITY IF EXISTS`);
        }
        break;
      }
      case "mysql":
        if (changes.some((c) => c !== "pk")) s.stmt(`ALTER TABLE ${name} MODIFY COLUMN ${col} ${colDef(src)}`);
        break;
      case "mssql": {
        if (changes.includes("type") || changes.includes("nullable")) {
          s.stmt(`ALTER TABLE ${name} ALTER COLUMN ${col} ${type} ${src.nullable ? "NULL" : "NOT NULL"}`);
        }
        if (changes.includes("default")) {
          const objName = (o.targetSchema ? `${o.targetSchema}.` : "") + t.name;
          s.parts.push([
            "DECLARE @df sysname;",
            `SELECT @df = dc.name FROM sys.default_constraints dc JOIN sys.columns c ON c.default_object_id = dc.object_id`,
            `  WHERE dc.parent_object_id = OBJECT_ID(N'${objName.replace(/'/g, "''")}') AND c.name = N'${src.name.replace(/'/g, "''")}';`,
            `IF @df IS NOT NULL EXEC(N'ALTER TABLE ${name.replace(/'/g, "''")} DROP CONSTRAINT [' + @df + N']');`,
            "GO",
          ].join("\n"));
          const def = mapDefault(src.default, o.sourceDialect, d);
          if (def !== null) s.stmt(`ALTER TABLE ${name} ADD DEFAULT ${def} FOR ${col}`);
        }
        if (changes.includes("autoIncrement")) s.comment(`IDENTITY change on ${src.name} requires a table rebuild in SQL Server (${tgt.autoIncrement ? "remove" : "add"} identity).`);
        break;
      }
    }
  }

  function sqliteRebuild(t: TableDiff) {
    const src = t.source!;
    const tmp = `${t.name}__devcat_new`;
    const common = src.columns.filter((c) => t.target!.columns.some((x) => x.name.toLowerCase() === c.name.toLowerCase())).map((c) => q(c.name)).join(", ");
    const lines = [
      `SQLite cannot alter column type / nullability / default / keys in place.`,
      `Table rebuild recipe for ${t.name} (uncomment to run):`,
      `PRAGMA foreign_keys = OFF;`,
      `BEGIN TRANSACTION;`,
      ...createTableSql(src, q(tmp), true).split("\n").map((l, i, arr) => (i === arr.length - 1 ? l + ";" : l)),
      `INSERT INTO ${q(tmp)} (${common}) SELECT ${common} FROM ${q(t.name)};`,
      `DROP TABLE ${q(t.name)};`,
      `ALTER TABLE ${q(tmp)} RENAME TO ${q(t.name)};`,
      ...src.indexes.filter((i) => !i.primary).map((i) => indexSql(t.name, i) + ";"),
      `COMMIT;`,
      `PRAGMA foreign_keys = ON;`,
    ];
    s.comment(lines.join("\n"));
  }

  function viewSql(v: ViewDiff) {
    const def = (v.sourceDef ?? "").trim().replace(/;\s*$/, "");
    const name = qualify(d, v.name, o.targetSchema);
    if (o.sourceDialect !== d) s.comment(`View ${v.name} was defined in ${o.sourceDialect}; verify the SQL is valid for ${d}.`);
    const isCreate = /^\s*create\s/i.test(def);
    const body = isCreate ? def.replace(/^[\s\S]*?\bas\b\s*/i, "") : def;
    switch (d) {
      case "postgres": s.stmt(`CREATE OR REPLACE VIEW ${name} AS\n${body}`); break;
      case "mysql": s.stmt(`CREATE OR REPLACE VIEW ${name} AS\n${body}`); break;
      case "mssql": s.stmt(`CREATE OR ALTER VIEW ${name} AS\n${body}`); break;
      case "sqlite":
        if (v.status === "different") s.stmt(`DROP VIEW IF EXISTS ${name}`);
        s.stmt(`CREATE VIEW ${name} AS\n${body}`);
        break;
    }
  }
}
